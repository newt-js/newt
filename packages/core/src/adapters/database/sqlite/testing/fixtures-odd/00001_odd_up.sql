CREATE TABLE odd (
  id TEXT PRIMARY KEY,
  version INTEGER NOT NULL,
  name TEXT COLLATE NOCASE NOT NULL,
  title VARCHAR(40) COLLATE NOCASE,
  note TEXT CHECK (note <> '') COLLATE RTRIM,
  "full name" TEXT COLLATE "NOCASE",
  code TEXT NOT NULL
);
CREATE UNIQUE INDEX odd_code ON odd (code COLLATE NOCASE);
