CREATE TABLE item (
  id VARCHAR(64) COLLATE utf8mb4_0900_bin PRIMARY KEY,
  version INTEGER NOT NULL,
  name VARCHAR(255) COLLATE utf8mb4_0900_bin,
  code VARCHAR(255) COLLATE utf8mb4_0900_bin NOT NULL UNIQUE,
  active BOOLEAN NOT NULL,
  data JSON,
  amount BIGINT
) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin;

CREATE TABLE things (
  id VARCHAR(64) COLLATE utf8mb4_0900_bin PRIMARY KEY,
  version INTEGER NOT NULL,
  name VARCHAR(255) COLLATE utf8mb4_0900_bin NOT NULL,
  size INTEGER NOT NULL,
  tag VARCHAR(255) COLLATE utf8mb4_0900_bin
) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin;

CREATE TABLE pair (
  id VARCHAR(64) COLLATE utf8mb4_0900_bin PRIMARY KEY,
  version INTEGER NOT NULL,
  tenant VARCHAR(64) COLLATE utf8mb4_0900_bin NOT NULL,
  code VARCHAR(64) COLLATE utf8mb4_0900_bin NOT NULL,
  email VARCHAR(255) COLLATE utf8mb4_0900_bin NOT NULL,
  UNIQUE (tenant, code)
) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin;

CREATE UNIQUE INDEX pair_email_unique ON pair (email);

CREATE TABLE `campaigns$template` (
  id VARCHAR(64) COLLATE utf8mb4_0900_bin PRIMARY KEY,
  version INTEGER NOT NULL,
  name VARCHAR(255) COLLATE utf8mb4_0900_bin NOT NULL UNIQUE,
  body VARCHAR(255) COLLATE utf8mb4_0900_bin
) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin;
