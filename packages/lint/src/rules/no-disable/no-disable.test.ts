import { asRule }    from '../../testing/testing'
import { tester }    from '../../testing/testing'
import { noDisable } from './no-disable'

// Rules ESLint knows, which the tester can be told of: the preset names newt's and those it turns on.
const OPTIONS = [{ rules: ['curly', 'eqeqeq'] }]

tester.run('no-disable', asRule(noDisable), {
  valid: [
    { code: '// eslint-disable-next-line curly -- generated by a tool that writes no braces\nif (a) b()', options: OPTIONS },
    { code: 'if (a) b() // eslint-disable-line curly -- generated by a tool', options: OPTIONS },
    { code: '// eslint-disable-next-line curly --- a reason after a longer dash\nif (a) b()', options: OPTIONS },
    // Rules of the app's own, which the preset does not keep.
    { code: '/* eslint-disable no-console */\nconsole.log(1)', options: OPTIONS },
    { code: '// eslint-disable-next-line no-console\nconsole.log(1)', options: OPTIONS },
    { code: '/* eslint no-console: "off" */\nconsole.log(1)', options: OPTIONS },
    { code: '/* eslint-enable curly */', options: OPTIONS },
    // A comment that only talks about the lint.
    { code: '// the eslint config lives at the root\n// eslint-disabled is no directive', options: OPTIONS },
  ],
  invalid: [
    { code: '/* eslint-disable curly */\nif (a) b()', options: OPTIONS, errors: [{ messageId: 'block', data: { kind: 'eslint-disable', rules: 'curly' } }] },
    { code: '// eslint-disable eqeqeq, no-console\na == b', options: OPTIONS, errors: [{ messageId: 'block', data: { kind: 'eslint-disable', rules: 'eqeqeq' } }] },
    { code: '/* eslint curly: "off", no-console: "off" */', options: OPTIONS, errors: [{ messageId: 'config', data: { rules: 'curly' } }] },
    { code: '// eslint-disable-next-line curly\nif (a) b()', options: OPTIONS, errors: [{ messageId: 'reason', data: { kind: 'eslint-disable-next-line', rules: 'curly' } }] },
    { code: 'if (a) b() // eslint-disable-line curly', options: OPTIONS, errors: [{ messageId: 'reason' }] },
    { code: '// eslint-disable-next-line curly --   \nif (a) b()', options: OPTIONS, errors: [{ messageId: 'reason' }] },
    { code: '// eslint-disable-next-line eqeqeq, no-console\na == b', options: OPTIONS, errors: [{ messageId: 'reason', data: { kind: 'eslint-disable-next-line', rules: 'eqeqeq' } }] },
  ],
})
